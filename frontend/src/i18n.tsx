type LangContextValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  locale: string;
  fmt: (v: number | undefined, digits?: number) => string;
  fmtDate: (s: string) => string;
};

const LangContext = createContext<LangContextValue>({
  lang: 'tr',
  setLang: () => {},
  t: (k) => k,
  locale: 'tr-TR',
  fmt: (v) => String(v),
  fmtDate: (s) => s,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => detectLang());
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* ignore */ }
    document.documentElement.lang = l;
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const t = useCallback((key: string) => dict[key]?.[lang] ?? key, [lang]);
  const locale = localeFor(lang);
  const fmt = useCallback((v: number | undefined, digits = 2) => {
    if (v === undefined || v === null || Number.isNaN(v as number)) return '—';
    return new Intl.NumberFormat(locale, { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(v);
  }, [locale]);
  const fmtDate = useCallback((s: string) => {
    try {
      return new Date(s).toLocaleDateString(locale, { day: '2-digit', month: 'short', year: 'numeric', timeZone: 'UTC' });
    } catch { return s; }
  }, [locale]);
  return <LangContext.Provider value={{ lang, setLang, t, locale, fmt, fmtDate }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
